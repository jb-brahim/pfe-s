// Fetch all generated reports
const getReports = async (req, res, next) => {
  try {
    const { role, _id: userId } = req.user;
    let filter = {};
    if (role === 'ADMIN' || req.user.approvalLevel >= 2) {
      const teamUserIds = await getTeamUserIds(req.user);
      filter.userId = { $in: teamUserIds };
    } else {
      filter.userId = userId;
    }
    const reports = await Report.find(filter).sort({ createdAt: -1 });
    res.json({ success: true, data: reports });
  } catch (error) {
    next(error);
  }
};

// Generate new report
const generateReport = async (req, res, next) => {
  try {
    const { type, dateRange, format } = req.body;
    const { _id: userId, name: creatorName } = req.user;

    if (!type || !dateRange || !format) {
      return res.status(400).json({ success: false, message: 'Type, date range, and format are required.' });
    }

    // 1. Parse Date Range
    let year = new Date().getFullYear();
    const yearMatch = dateRange.match(/\b(20\d{2})\b/);
    if (yearMatch) {
      year = parseInt(yearMatch[1]);
    }

    let startDate, endDate;
    if (dateRange.includes('to')) {
      const parts = dateRange.split('to').map(s => s.trim());
      startDate = new Date(parts[0]);
      endDate = new Date(parts[1]);
      endDate.setHours(23, 59, 59, 999);
    } else if (dateRange.includes('Q1')) {
      startDate = new Date(year, 0, 1);
      endDate = new Date(year, 2, 31, 23, 59, 59, 999);
    } else if (dateRange.includes('Q2')) {
      startDate = new Date(year, 3, 1);
      endDate = new Date(year, 5, 30, 23, 59, 59, 999);
    } else if (dateRange.includes('Q3') || dateRange.includes('Jul - Sep')) {
      startDate = new Date(year, 6, 1);
      endDate = new Date(year, 8, 30, 23, 59, 59, 999);
    } else if (dateRange.includes('Q4')) {
      startDate = new Date(year, 9, 1);
      endDate = new Date(year, 11, 31, 23, 59, 59, 999);
    } else {
      // Default full year
      startDate = new Date(year, 0, 1);
      endDate = new Date(year, 11, 31, 23, 59, 59, 999);
    }

    // 2. Fetch approved invoices for the organization
    const { role } = req.user;
    let invoiceFilter = {
      createdAt: { $gte: startDate, $lte: endDate }
    };
    
    if (role === 'ADMIN' || req.user.approvalLevel >= 2) {
      const teamUserIds = await getTeamUserIds(req.user);
      invoiceFilter.userId = { $in: teamUserIds };
    } else {
      invoiceFilter.userId = userId;
    }

    const invoices = await Invoice.find(invoiceFilter).populate('userId', 'name email');
    const invoiceIds = invoices.map(i => i._id);

    const dataList = await ExtractedData.find({
      invoiceId: { $in: invoiceIds }
    }).sort({ date: 1, createdAt: 1 }).lean();

    // Fetch AuditLogs for these invoices to find who approved/rejected
    const AuditLog = require('../models/AuditLog');
    const auditLogs = await AuditLog.find({
      entityId: { $in: invoiceIds },
      action: { $in: ['INVOICE_APPROVE', 'INVOICE_REJECT'] }
    }).populate('userId', 'name').sort({ timestamp: -1 }).lean();

    const actionByMap = {};
    auditLogs.forEach(log => {
      if (!actionByMap[log.entityId.toString()]) {
        actionByMap[log.entityId.toString()] = log.userId ? log.userId.name : 'System';
      }
    });

    const invoiceMap = {};
    invoices.forEach(inv => {
      invoiceMap[inv._id.toString()] = inv;
    });

    dataList.forEach(item => {
      const invId = item.invoiceId.toString();
      const inv = invoiceMap[invId];
      item.uploadedBy = inv && inv.userId ? inv.userId.name : 'Unknown';
      item.status = inv ? inv.status : 'UNKNOWN';
      item.actionBy = actionByMap[invId] || 'N/A';
    });

    // 3. Define report title
    const shortType = type.split(' ')[0];
    const title = `${dateRange} ${type}`;
    const cleanTypeFilename = type.toLowerCase().replace(/[^a-z0-9]/g, '_');
    const timestamp = Date.now();
    const fileExtension = format === 'PDF' ? 'pdf' : 'csv';
    const filename = `report_${cleanTypeFilename}_${timestamp}.${fileExtension}`;
    
    const reportsDir = path.join(__dirname, '..', '..', 'uploads', 'reports');
    if (!fs.existsSync(reportsDir)) {
      fs.mkdirSync(reportsDir, { recursive: true });
    }
    const filePath = path.join(reportsDir, filename);
    const fileUrl = `/uploads/reports/${filename}`;

    // 4. Generate the physical file
    let fileBuffer;
    let sizeStr = '0 KB';
    if (format === 'PDF') {
      const pdfBytes = await generatePDFReport({
        title,
        type,
        dateRange,
        dataList,
        creatorName
      });
      fileBuffer = Buffer.from(pdfBytes);
      fs.writeFileSync(filePath, fileBuffer);
      sizeStr = `${(fileBuffer.length / (1024 * 1024)).toFixed(1)} MB`;
    } else {
      // CSV or XLSX
      const csvString = generateCSVReport({
        type,
        dateRange,
        dataList
      });
      fileBuffer = Buffer.from(csvString);
      fs.writeFileSync(filePath, fileBuffer);
      sizeStr = `${(fileBuffer.length / 1024).toFixed(1)} KB`;
    }

    // 5. Write to DB
    const newReport = await Report.create({
      title,
      type,
      format,
      dateRange,
      fileUrl,
      size: sizeStr,
      status: 'Ready',
      userId
    });

    res.status(201).json({ success: true, data: newReport });
  } catch (error) {
    next(error);
  }
};

// Delete report
const deleteReport = async (req, res, next) => {
  try {
    const { id } = req.params;
    const { role, _id: userId } = req.user;

    const report = await Report.findById(id);
    if (!report) {
      return res.status(404).json({ success: false, message: 'Report not found' });
    }

    // Authorization
    if (role === 'ACCOUNTANT' && report.userId.toString() !== userId.toString()) {
      return res.status(403).json({ success: false, message: 'Unauthorized' });
    }

    // Delete file
    const absolutePath = path.join(__dirname, '..', '..', report.fileUrl);
    if (fs.existsSync(absolutePath)) {
      fs.unlinkSync(absolutePath);
    }

    await Report.findByIdAndDelete(id);
    res.json({ success: true, message: 'Report deleted successfully' });
  } catch (error) {
    next(error);
  }
};

